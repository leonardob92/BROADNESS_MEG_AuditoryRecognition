%% ------------------------ Repeated/mixed ANOVA --------------------------

function omnibus = mixed_anova_timecourse(metricData, time, groupLabels, opts)
nTime = size(metricData,1);
nConditions = size(metricData,2);

omnibus.Time = time;
omnibus.Condition = initialize_anova_effect(nTime);
omnibus.Group = initialize_anova_effect(nTime);
omnibus.Interaction = initialize_anova_effect(nTime);

for timeIndex = 1:nTime
    values = reshape(metricData(timeIndex,:,:), nConditions, size(metricData,3))';
    valid = all(isfinite(values),2) & isfinite(groupLabels);
    values = values(valid,:);
    labels = groupLabels(valid);
    if isempty(values)
        continue
    end

    effects = calculate_mixed_anova(values, labels);
    effectNames = {'Condition','Group','Interaction'};
    for effectIndex = 1:length(effectNames)
        effectName = effectNames{effectIndex};
        omnibus.(effectName).F(timeIndex) = effects.(effectName).F;
        omnibus.(effectName).DF1(timeIndex) = effects.(effectName).DF1;
        omnibus.(effectName).DF2(timeIndex) = effects.(effectName).DF2;
        omnibus.(effectName).P(timeIndex) = effects.(effectName).P;
        omnibus.(effectName).EpsilonGG(timeIndex) = effects.(effectName).EpsilonGG;
        omnibus.(effectName).DF1_GG(timeIndex) = effects.(effectName).DF1_GG;
        omnibus.(effectName).DF2_GG(timeIndex) = effects.(effectName).DF2_GG;
        omnibus.(effectName).P_GG(timeIndex) = effects.(effectName).P_GG;
    end
end

effectNames = {'Condition','Group','Interaction'};
for effectIndex = 1:length(effectNames)
    effectName = effectNames{effectIndex};
    omnibus.(effectName).P_FDR = adjust_pvalues(omnibus.(effectName).P_GG, opts);
    omnibus.(effectName).Significant = ...
        omnibus.(effectName).P_FDR < opts.alpha;
end
end

function effect = initialize_anova_effect(nTime)
effect.F = nan(nTime,1);
effect.DF1 = nan(nTime,1);
effect.DF2 = nan(nTime,1);
effect.P = nan(nTime,1);
effect.EpsilonGG = nan(nTime,1);
effect.DF1_GG = nan(nTime,1);
effect.DF2_GG = nan(nTime,1);
effect.P_GG = nan(nTime,1);
effect.P_FDR = nan(nTime,1);
effect.Significant = false(nTime,1);
end

function effects = calculate_mixed_anova(values, groupLabels)
effects.Condition = empty_anova_value();
effects.Group = empty_anova_value();
effects.Interaction = empty_anova_value();

nParticipants = size(values,1);
nConditions = size(values,2);
groupLevels = unique(groupLabels, 'stable');
nGroups = length(groupLevels);

if nParticipants < 2
    return
end

grandMean = mean(values(:));
participantMeans = mean(values,2);
conditionMeans = mean(values,1);

if nConditions > 1
    conditionSS = nParticipants * sum((conditionMeans-grandMean).^2);
else
    conditionSS = 0;
end

if nGroups == 1
    if nConditions < 2
        return
    end
    errorValues = values-participantMeans-conditionMeans+grandMean;
    errorSS = sum(errorValues(:).^2);
    conditionDF = nConditions-1;
    errorDF = (nParticipants-1)*(nConditions-1);
    effects.Condition = make_anova_value(conditionSS, conditionDF, errorSS, errorDF);
    epsilonGG = greenhouse_geisser_epsilon(values, groupLabels);
    effects.Condition = apply_greenhouse_geisser(effects.Condition, epsilonGG);
    return
end

groupMeans = nan(nGroups,1);
groupConditionMeans = nan(nGroups,nConditions);
groupSizes = nan(nGroups,1);
subjectWithinGroupSS = 0;

for group = 1:nGroups
    groupMask = groupLabels == groupLevels(group);
    groupSizes(group) = sum(groupMask);
    groupMeans(group) = mean(values(groupMask,:), 'all');
    groupConditionMeans(group,:) = mean(values(groupMask,:),1);
    subjectWithinGroupSS = subjectWithinGroupSS + ...
        nConditions*sum((participantMeans(groupMask)-groupMeans(group)).^2);
end

groupSS = nConditions * sum(groupSizes.*(groupMeans-grandMean).^2);
interactionSS = 0;
errorSS = 0;
for group = 1:nGroups
    groupMask = groupLabels == groupLevels(group);
    interactionTerms = groupConditionMeans(group,:)-groupMeans(group)-conditionMeans+grandMean;
    interactionSS = interactionSS + groupSizes(group)*sum(interactionTerms.^2);

    groupValues = values(groupMask,:);
    groupParticipantMeans = participantMeans(groupMask);
    residuals = groupValues-groupParticipantMeans-groupConditionMeans(group,:)+groupMeans(group);
    errorSS = errorSS+sum(residuals(:).^2);
end

groupDF = nGroups-1;
subjectWithinGroupDF = nParticipants-nGroups;
effects.Group = make_anova_value(groupSS, groupDF, ...
    subjectWithinGroupSS, subjectWithinGroupDF);

if nConditions > 1
    conditionDF = nConditions-1;
    interactionDF = (nGroups-1)*(nConditions-1);
    errorDF = (nParticipants-nGroups)*(nConditions-1);
    effects.Condition = make_anova_value(conditionSS, conditionDF, errorSS, errorDF);
    effects.Interaction = make_anova_value(interactionSS, interactionDF, errorSS, errorDF);
    epsilonGG = greenhouse_geisser_epsilon(values, groupLabels);
    effects.Condition = apply_greenhouse_geisser(effects.Condition, epsilonGG);
    effects.Interaction = apply_greenhouse_geisser(effects.Interaction, epsilonGG);
end
end

function effect = empty_anova_value()
effect = struct('F',NaN,'DF1',NaN,'DF2',NaN,'P',NaN, ...
    'EpsilonGG',NaN,'DF1_GG',NaN,'DF2_GG',NaN,'P_GG',NaN);
end

function effect = make_anova_value(effectSS, effectDF, errorSS, errorDF)
effect = empty_anova_value();
if effectDF < 1 || errorDF < 1 || errorSS < 0
    return
end

effectMeanSquare = effectSS/effectDF;
errorMeanSquare = errorSS/errorDF;
if errorMeanSquare == 0
    if effectMeanSquare == 0
        F = 0;
        P = 1;
    else
        F = Inf;
        P = 0;
    end
else
    F = effectMeanSquare/errorMeanSquare;
    P = 1-fcdf(F,effectDF,errorDF);
end

effect.F = F;
effect.DF1 = effectDF;
effect.DF2 = errorDF;
effect.P = P;
effect.EpsilonGG = 1;
effect.DF1_GG = effectDF;
effect.DF2_GG = errorDF;
effect.P_GG = P;
end

function epsilonGG = greenhouse_geisser_epsilon(values, groupLabels)
nConditions = size(values,2);
if nConditions <= 2
    epsilonGG = 1;
    return
end

groupLevels = unique(groupLabels, 'stable');
residualValues = values;
for group = 1:length(groupLevels)
    groupMask = groupLabels == groupLevels(group);
    residualValues(groupMask,:) = values(groupMask,:) - mean(values(groupMask,:),1);
end

covarianceMatrix = cov(residualValues);
centeringMatrix = eye(nConditions)-ones(nConditions)/nConditions;
centeredCovariance = centeringMatrix*covarianceMatrix*centeringMatrix;
denominator = (nConditions-1)*trace(centeredCovariance*centeredCovariance);
if denominator <= 0 || ~isfinite(denominator)
    epsilonGG = 1;
else
    epsilonGG = trace(centeredCovariance)^2/denominator;
    epsilonGG = min(1,max(1/(nConditions-1),epsilonGG));
end
end

function effect = apply_greenhouse_geisser(effect, epsilonGG)
if ~isfinite(effect.F) || ~isfinite(effect.DF1) || ~isfinite(effect.DF2)
    return
end

effect.EpsilonGG = epsilonGG;
effect.DF1_GG = effect.DF1*epsilonGG;
effect.DF2_GG = effect.DF2*epsilonGG;
effect.P_GG = 1-fcdf(effect.F,effect.DF1_GG,effect.DF2_GG);
end

%% ------------------------------ FDR ------------------------------------

function adjustedP = adjust_pvalues(pValues, opts)
if strcmpi(opts.fdr, 'off')
    adjustedP = pValues;
else
    adjustedP = benjamini_hochberg(pValues);
end
end

function adjustedP = benjamini_hochberg(pValues)
originalSize = size(pValues);
pValues = pValues(:);
adjustedP = nan(size(pValues));
validIndices = find(isfinite(pValues));
if isempty(validIndices)
    adjustedP = reshape(adjustedP, originalSize);
    return
end

[sortedP, sortOrder] = sort(pValues(validIndices));
nValid = length(sortedP);
adjustedSorted = sortedP.*nValid./(1:nValid)';
for index = nValid-1:-1:1
    adjustedSorted(index) = min(adjustedSorted(index), adjustedSorted(index+1));
end
adjustedSorted = min(adjustedSorted,1);

restored = nan(nValid,1);
restored(sortOrder) = adjustedSorted;
adjustedP(validIndices) = restored;
adjustedP = reshape(adjustedP, originalSize);
end
