function results = run_scalar_metric_tests(metricData, time, conditionNames, ...
    groupMembers, groupNames, groupLabels, testType, opts)

results.ConditionComparisons = {};
results.GroupComparisons = {};
results.Interactions = {};
results.Omnibus = struct();

nConditions = size(metricData,2);
nGroups = length(groupMembers);
allParticipants = unique([groupMembers{:}], 'stable');

if strcmpi(opts.pairwise, 'on')
    conditionContexts = groupMembers;
    conditionContextNames = groupNames;
    if nGroups > 1
        conditionContexts = [{allParticipants} groupMembers];
        conditionContextNames = [{'AllParticipants'} groupNames];
    end

    counter = 0;
    for context = 1:length(conditionContexts)
        participants = conditionContexts{context};
        for cond1 = 1:nConditions-1
            for cond2 = cond1+1:nConditions
                A = extract_metric_data(metricData, cond1, participants);
                B = extract_metric_data(metricData, cond2, participants);
                counter = counter + 1;
                results.ConditionComparisons{counter} = scalar_paired_comparison( ...
                    A, B, time, conditionNames{cond1}, conditionNames{cond2}, ...
                    conditionContextNames{context}, 'conditions', testType);
            end
        end
    end

    counter = 0;
    for cond = 1:nConditions
        for group1 = 1:nGroups-1
            for group2 = group1+1:nGroups
                A = extract_metric_data(metricData, cond, groupMembers{group1});
                B = extract_metric_data(metricData, cond, groupMembers{group2});
                counter = counter + 1;
                results.GroupComparisons{counter} = scalar_independent_comparison( ...
                    A, B, time, groupNames{group1}, groupNames{group2}, ...
                    conditionNames{cond}, 'groups', testType);
            end
        end
    end

    counter = 0;
    for group1 = 1:nGroups-1
        for group2 = group1+1:nGroups
            for cond1 = 1:nConditions-1
                for cond2 = cond1+1:nConditions
                    A1 = extract_metric_data(metricData, cond1, groupMembers{group1});
                    A2 = extract_metric_data(metricData, cond2, groupMembers{group1});
                    B1 = extract_metric_data(metricData, cond1, groupMembers{group2});
                    B2 = extract_metric_data(metricData, cond2, groupMembers{group2});
                    contextLabel = [conditionNames{cond1} '_minus_' conditionNames{cond2}];
                    counter = counter + 1;
                    results.Interactions{counter} = scalar_independent_comparison( ...
                        A1-A2, B1-B2, time, groupNames{group1}, groupNames{group2}, ...
                        contextLabel, 'interaction', testType);
                end
            end
        end
    end

    results.ConditionComparisons = apply_scalar_fdr_family( ...
        results.ConditionComparisons, testType, opts);
    results.GroupComparisons = apply_scalar_fdr_family( ...
        results.GroupComparisons, testType, opts);
    results.Interactions = apply_scalar_fdr_family( ...
        results.Interactions, testType, opts);
end

if strcmpi(opts.omnibus, 'on')
    results.Omnibus.Parametric = mixed_anova_timecourse( ...
        metricData, time, groupLabels, opts);
end
end

function data = extract_metric_data(metricData, condition, participants)
data = metricData(:,condition,participants);
data = reshape(data, size(metricData,1), length(participants));
end

function comparison = scalar_paired_comparison(A, B, time, level1, level2, ...
    context, comparisonType, testType)

nTime = size(A,1);
comparison = package_scalar_comparison(A, B, time, level1, level2, ...
    context, comparisonType);

if any(strcmp(testType, {'parametric','both'}))
    result = initialize_scalar_test(nTime);
    for timeIndex = 1:nTime
        valid = isfinite(A(timeIndex,:)) & isfinite(B(timeIndex,:));
        valuesA = A(timeIndex,valid);
        valuesB = B(timeIndex,valid);
        result.N1(timeIndex) = length(valuesA);
        result.N2(timeIndex) = length(valuesB);
        if length(valuesA) < 2
            continue
        end
        [~, result.P(timeIndex), ~, statistics] = ttest(valuesA, valuesB);
        result.Statistic(timeIndex) = statistics.tstat;
        result.DF(timeIndex) = statistics.df;
    end
    comparison.Parametric = result;
end

if any(strcmp(testType, {'nonparametric','both'}))
    result = initialize_scalar_test(nTime);
    for timeIndex = 1:nTime
        valid = isfinite(A(timeIndex,:)) & isfinite(B(timeIndex,:));
        valuesA = A(timeIndex,valid);
        valuesB = B(timeIndex,valid);
        result.N1(timeIndex) = length(valuesA);
        result.N2(timeIndex) = length(valuesB);
        if length(valuesA) < 2 || all(valuesA == valuesB)
            if length(valuesA) >= 2 && all(valuesA == valuesB)
                result.P(timeIndex) = 1;
                result.Statistic(timeIndex) = 0;
            end
            continue
        end
        try
            [result.P(timeIndex), ~, statistics] = signrank(valuesA, valuesB);
            if isfield(statistics, 'zval')
                result.Statistic(timeIndex) = statistics.zval;
            elseif isfield(statistics, 'signedrank')
                result.Statistic(timeIndex) = statistics.signedrank;
            end
        catch
            result.P(timeIndex) = NaN;
        end
    end
    comparison.Nonparametric = result;
end
end

function comparison = scalar_independent_comparison(A, B, time, level1, level2, ...
    context, comparisonType, testType)

nTime = size(A,1);
comparison = package_scalar_comparison(A, B, time, level1, level2, ...
    context, comparisonType);

if any(strcmp(testType, {'parametric','both'}))
    result = initialize_scalar_test(nTime);
    for timeIndex = 1:nTime
        valuesA = A(timeIndex,isfinite(A(timeIndex,:)));
        valuesB = B(timeIndex,isfinite(B(timeIndex,:)));
        result.N1(timeIndex) = length(valuesA);
        result.N2(timeIndex) = length(valuesB);
        if length(valuesA) < 2 || length(valuesB) < 2
            continue
        end
        [~, result.P(timeIndex), ~, statistics] = ...
            ttest2(valuesA, valuesB, 'Vartype', 'unequal');
        result.Statistic(timeIndex) = statistics.tstat;
        result.DF(timeIndex) = statistics.df;
    end
    comparison.Parametric = result;
end

if any(strcmp(testType, {'nonparametric','both'}))
    result = initialize_scalar_test(nTime);
    for timeIndex = 1:nTime
        valuesA = A(timeIndex,isfinite(A(timeIndex,:)));
        valuesB = B(timeIndex,isfinite(B(timeIndex,:)));
        result.N1(timeIndex) = length(valuesA);
        result.N2(timeIndex) = length(valuesB);
        if isempty(valuesA) || isempty(valuesB)
            continue
        end
        try
            [result.P(timeIndex), ~, statistics] = ranksum(valuesA, valuesB);
            if isfield(statistics, 'zval')
                result.Statistic(timeIndex) = statistics.zval;
            elseif isfield(statistics, 'ranksum')
                result.Statistic(timeIndex) = statistics.ranksum;
            end
        catch
            result.P(timeIndex) = NaN;
        end
    end
    comparison.Nonparametric = result;
end
end

